#!/usr/bin/env python3
"""Generate a brand style for the video-pizarra styles engine from its 'minimal' style.

Run inside a project copied from template-estilos/:
    python3 brand_style.py klip      -> styles/klip.js   (then style: 'klip' in video.js)
    python3 brand_style.py ryj       -> styles/ryj.js    (then style: 'ryj'  in video.js)

The upstream file is patched at build time (not copied into this repo) because
video-pizarra has no license. Every replacement must match exactly once, so an
upstream change fails loudly instead of producing a half-branded style.
"""
import sys
from pathlib import Path

BRANDS = {
    'klip': {
        'name': 'Klip Studio',
        'bg': '#EBEBEB', 'ink': '#1D1D1C', 'muted': '#5D5D5C', 'line': 'rgba(29,29,28,.12)',
        'accent': '#E40E20', 'panel': '#F7F7F5', 'dim': '#9A9A98', 'body': '#3A3A39',
        'caption_bg': 'rgba(235,235,235,.9)', 'button': '#E40E20', 'button_text': '#FFFFFF',
        'display': 'Montserrat', 'body_font': 'Montserrat',
        'fonts': 'Montserrat:wght@300;400;500;600;800&family=JetBrains+Mono:wght@400',
        'upper': False, 'display_weight': 700,
    },
    'ryj': {
        'name': 'Respect Your Journey',
        'bg': '#121212', 'ink': '#F2EFE8', 'muted': '#8C8C8C', 'line': 'rgba(242,239,232,.14)',
        'accent': '#F5B51B', 'panel': '#2B2B2B', 'dim': '#5E5E5E', 'body': '#CFCBC2',
        'caption_bg': 'rgba(18,18,18,.88)', 'button': '#F5B51B', 'button_text': '#121212',
        'display': 'Anton', 'body_font': 'Poppins',
        'fonts': 'Anton&family=Poppins:wght@400;500;600;800&family=JetBrains+Mono:wght@400',
        'upper': True,
    },
}


def build(src: str, b: dict, brand_id: str) -> str:
    d, f = b['display'], b['body_font']
    reps = [
        ("id: 'minimal', name: 'Minimal blanco'", f"id: '{brand_id}', name: '{b['name']}'"),
        ("const BG = '#FAFAF7', INK = '#161616', MUTED = '#8C8C88', LINE = 'rgba(22,22,22,.10)'",
         f"const BG = '{b['bg']}', INK = '{b['ink']}', MUTED = '{b['muted']}', LINE = '{b['line']}'"),
        ("let ACC = '#FF4F00'", f"let ACC = '{b['accent']}'"),
        ("fonts: 'Inter+Tight:wght@200;300;400;600&family=Inter:wght@400;500&family=JetBrains+Mono:wght@400'",
         f"fonts: '{b['fonts']}'"),
        ("panel: '#FFFFFF'", f"panel: '{b['panel']}'"),
        ("ctx.fillStyle = '#FFFFFF'; ctx.fill();\n    ctx.shadowColor", f"ctx.fillStyle = '{b['panel']}'; ctx.fill();\n    ctx.shadowColor"),
        ("'#A6A6A2'", f"'{b['dim']}'"),
        ("'#6E6E6A'", f"'{b['body']}'"),
        ("'#B4B4B0'", f"'{b['dim']}'"),
        ("'rgba(250,250,247,.85)'", f"'{b['caption_bg']}'"),
        ("'rgba(22,22,22,.25)'", f"'{b['line']}'"),
        ("ctx.fillStyle = INK; ctx.fill(); ctx.restore();\n    para(K, str, L.inset(b, b.h * 0.4, b.h * 0.22), e, { font: sz => K.S.type.label(sz), color: '#FFFFFF'",
         f"ctx.fillStyle = '{b['button']}'; ctx.fill(); ctx.restore();\n    para(K, str, L.inset(b, b.h * 0.4, b.h * 0.22), e, {{ font: sz => K.S.type.label(sz), color: '{b['button_text']}'"),
        ("barColor: '#F1F1EE'", f"barColor: '{b['panel']}'"),
    ]
    out = src
    for old, new in reps:
        n = out.count(old)
        if n != 1:
            sys.exit(f"brand_style: expected 1 match, found {n}: {old[:70]!r} (upstream minimal.js changed?)")
        out = out.replace(old, new)
    # fonts: every "Inter Tight" is the display face, every bare Inter the body face
    out = out.replace('"Inter Tight"', f'"{d}"').replace(' Inter`', f' {f}`').replace(' Inter\'', f' {f}\'')
    if b.get('display_weight'):  # minimal's display face is 300; some brands want heavier headlines
        old = 'display: s => `300 ${s}px'
        if out.count(old) != 1:
            sys.exit('brand_style: display weight pattern not found (upstream minimal.js changed?)')
        out = out.replace(old, f"display: s => `{b['display_weight']} ${{s}}px")
    if b['upper']:  # RYJ headlines are always uppercase
        out = out.replace("headline(K, str, box, p, s, o = {}) {", "headline(K, str, box, p, s, o = {}) {\n    str = str.toUpperCase();", 1)
    return f"// Generated by klip-video-pizarra/scripts/brand_style.py ({brand_id}) from minimal.js. Regenerate, don't hand-edit.\n" + out


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in BRANDS:
        sys.exit(f"usage: brand_style.py {{{'|'.join(BRANDS)}}}")
    brand_id = sys.argv[1]
    src = Path('styles/minimal.js')
    if not src.exists():
        sys.exit('brand_style: run inside a project copied from template-estilos/ (styles/minimal.js not found)')
    dst = Path('styles') / f'{brand_id}.js'
    dst.write_text(build(src.read_text(), BRANDS[brand_id], brand_id))
    print(f"wrote {dst}: set style: '{brand_id}' in video.js")


if __name__ == '__main__':
    main()
